/**
 * يكتب pr-safe-auth-production.js من متغير البيئة PR_SAFE_AUTH_API_BASE
 * الاستخدام: set PR_SAFE_AUTH_API_BASE=https://api.example.com && npm run set:production-api
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'pr-safe-auth-production.js');
const base = String(process.env.PR_SAFE_AUTH_API_BASE || process.argv[2] || '').trim().replace(/\/+$/, '');

if (!base) {
    console.error('Usage: PR_SAFE_AUTH_API_BASE=https://api.example.com npm run set:production-api');
    process.exit(1);
}
if (!/^https:\/\//i.test(base)) {
    console.error('PR_SAFE_AUTH_API_BASE must start with https://');
    process.exit(1);
}

const body =
    '/**\n' +
    ' * Generated by npm run set:production-api — do not commit secrets here (URL only).\n' +
    ' */\n' +
    "window.__PR_SAFE_AUTH_API_BASE__ = '" +
    base.replace(/\\/g, '\\\\').replace(/'/g, "\\'") +
    "';\n";

fs.writeFileSync(out, body, 'utf8');
console.log('Wrote', out, '→', base);
